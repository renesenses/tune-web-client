#!/usr/bin/env node
/** Country ownership of the existing land particles, not individual locations.
 * Natural Earth (public domain), pinned source; no runtime GIS dependency.
 * node scripts/genererPaysTerre.mjs [countries.geojson]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/117488dc884bad03366ff727eca013e434615127/geojson/ne_110m_admin_0_map_units.geojson';
const raw = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (async () => { const r = await fetch(source); if (!r.ok) throw new Error(`Natural Earth: ${r.status}`); return r.text(); })();
const land = readFileSync(root + 'src/lib/champCercle/pointsTerre.ts', 'utf8');
const numbers = /POINTS_TERRE = '([^']+)'/.exec(land)[1].split(',').map(Number);
const inside = (x, y, ring) => {
  let yes = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) yes = !yes;
  }
  return yes;
};
const polygons = JSON.parse(raw).features.flatMap((f) => {
  const code = f.properties.ISO_A2_EH ?? f.properties.ISO_A2;
  if (!/^[A-Z]{2}$/.test(code)) return [];
  const list = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  return list.map((rings) => {
    const xs = rings[0].map((p) => p[0]), ys = rings[0].map((p) => p[1]);
    return { code, rings, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] };
  });
});
const codes = [];
for (let i = 0; i < numbers.length; i += 2) {
  const lat = numbers[i] / 10, lon = numbers[i + 1] / 10;
  const p = polygons.find(({ box: b, rings }) => lon >= b[0] && lon <= b[2] && lat >= b[1] && lat <= b[3]
    && inside(lon, lat, rings[0]) && !rings.slice(1).some((r) => inside(lon, lat, r)));
  codes.push(p?.code ?? '--');
}
const sha = (text) => createHash('sha256').update(text).digest('hex');
writeFileSync(root + 'src/lib/champCercle/paysTerre.ts', `/** Generated by scripts/genererPaysTerre.mjs. Natural Earth, public domain.
 * Source: ${source}
 * Source SHA256: ${sha(raw)}
 * Land file SHA256: ${sha(land)}
 * Two characters per existing land particle; -- means not assigned.
 * 110m boundaries omit some small territories; the accessible country list is complete.
 */\nexport const PAYS_TERRE = '${codes.join('')}';\n`);
console.log(`${codes.length} land particles, ${new Set(codes.filter((c) => c !== '--')).size} countries`);
